#!/usr/bin/env python3
"""Scan assets/sprites and write assets/sprites/manifest.js (what the game loads at start-up).

File naming:
  <name>.png                     single legacy view, art facing right ('e')
  <name>_<dir>_<frame>.png       directional views; dir = n ne e se s sw w nw, frame = 0,1,2...
  <name>/<dir>_<frame>.png       the same, but one folder per unit (preferred; the folder name is the unit name).
                                 <name>/meta.json holds that unit's own h / muz overrides.
Optional assets/sprites/meta.json overrides per sprite, e.g.
  { "tank": { "h": 90, "muz": { "s": [40, 52], "e": [60, 50] } } }
  h   = height in world px (default comes from SPR_DEF in game.js)
  muz = where enemy plasma leaves the weapon for a view: [x offset px from centre (+right, art-space), height px]
"""
import json, os, re, sys

DIRS = ['n', 'nne', 'ne', 'ene', 'e', 'ese', 'se', 'sse', 's', 'ssw', 'sw', 'wsw', 'w', 'wnw', 'nw', 'nnw',
        'a0', 'a30', 'a60', 'a90', 'a120', 'a150', 'a180', 'a210', 'a240', 'a270', 'a300', 'a330']
PAT = re.compile(r'^([a-z0-9_]+?)(?:_(n|nne|ne|ene|e|ese|se|sse|s|ssw|sw|wsw|w|wnw|nw|nnw|a\d+)_(\d+))?\.png$')

SUBPAT = re.compile(r'^(n|nne|ne|ene|e|ese|se|sse|s|ssw|sw|wsw|w|wnw|nw|nnw|a\d+)_(\d+)\.png$')

def build(root):
    meta = {}
    mp = os.path.join(root, 'meta.json')
    if os.path.exists(mp):
        meta = json.load(open(mp))
    found = {}
    for f in sorted(os.listdir(root)):
        m = PAT.match(f)
        if not m:
            continue
        name, d, fr = m.group(1), m.group(2), m.group(3)
        if d is None:
            found.setdefault(name, {}).setdefault('e', {})[0] = f      # legacy single view faces right
        else:
            found.setdefault(name, {}).setdefault(d, {})[int(fr)] = f
    for name in sorted(os.listdir(root)):                                  # one folder per unit
        sub = os.path.join(root, name)
        if not os.path.isdir(sub) or name.startswith('_') or name.startswith('.'):
            continue
        if os.path.exists(os.path.join(sub, 'meta.json')):
            meta[name] = json.load(open(os.path.join(sub, 'meta.json')))
        for f in sorted(os.listdir(sub)):
            m = SUBPAT.match(f)
            if m:
                found.setdefault(name, {}).setdefault(m.group(1), {})[int(m.group(2))] = name + '/' + f
    out = {}
    for name, views in found.items():
        ent = {'dirs': {}}
        for d in DIRS:
            if d in views:
                v = views[d]
                files = [v[i] for i in sorted(v)]
                dv = {'files': files}
                mz = (meta.get(name, {}).get('muz') or {}).get(d)
                if mz:
                    dv['muz'] = mz
                vt = (meta.get(name, {}).get('vents') or {}).get(d)
                if vt:
                    dv['vents'] = vt       # [[x, y], ...] normalised spots on the solid body where boss fire and smoke may start
                lt = (meta.get(name, {}).get('lights') or {}).get(d)
                if lt:
                    dv['lights'] = lt      # [[x, height], ...] spotlight / eye positions in world px (x from centre, height from the sprite bottom)
                ent['dirs'][d] = dv
        if 'h' in meta.get(name, {}):
            ent['h'] = meta[name]['h']
        out[name] = ent
    with open(os.path.join(root, 'manifest.js'), 'w') as fh:
        fh.write('// generated by tools/build_manifest.py - do not edit by hand\nwindow.SPRITE_MANIFEST = ' + json.dumps(out, indent=1) + ';\n')
    return out

def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'sprites')
    out = build(root)
    for name, ent in sorted(out.items()):
        print('%-12s %s' % (name, ' '.join('%s%s' % (d, 'x%d' % len(v['files']) if len(v['files']) > 1 else '') for d, v in ent['dirs'].items())))

if __name__ == '__main__':
    main()
